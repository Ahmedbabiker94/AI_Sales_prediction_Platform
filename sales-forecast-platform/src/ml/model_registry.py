import mlflow

from mlflow.tracking import MlflowClient


MLFLOW_TRACKING_URI = "http://127.0.0.1:5000"

MODEL_NAME = "sales_forecasting_model"


mlflow.set_tracking_uri(
    MLFLOW_TRACKING_URI
)

client = MlflowClient()


# ============================================================
# MODEL REGISTRATION
# ============================================================

def register_model(run_id: str) -> int:
    """
    Register the model artifact generated by an MLflow run.
    """

    model_uri = (
        f"runs:/{run_id}/model"
    )

    registered_model = mlflow.register_model(
        model_uri=model_uri,
        name=MODEL_NAME
    )

    return int(
        registered_model.version
    )


# ============================================================
# MODEL ALIASES
# ============================================================

def promote_model_to_production(
    version: int
):
    """
    Assign the production alias to a model version.
    """

    client.set_registered_model_alias(
        name=MODEL_NAME,
        alias="production",
        version=version
    )

    print(
        f"Model version {version} "
        f"assigned to @production"
    )


def promote_model_to_staging(
    version: int
):
    """
    Assign the staging alias to a model version.
    """

    client.set_registered_model_alias(
        name=MODEL_NAME,
        alias="staging",
        version=version
    )

    print(
        f"Model version {version} "
        f"assigned to @staging"
    )


# ============================================================
# MODEL URI HELPERS
# ============================================================

def get_production_model_uri() -> str:
    """
    Return the URI of whatever model version is
    currently assigned to @production.
    """

    return (
        f"models:/{MODEL_NAME}@production"
    )


def get_staging_model_uri() -> str:
    """
    Return the URI of whatever model version is
    currently assigned to @staging.
    """

    return (
        f"models:/{MODEL_NAME}@staging"
    )


def get_model_version_uri(
    version: int
) -> str:
    """
    Return the URI for a specific model version.
    """

    return (
        f"models:/{MODEL_NAME}/{version}"
    )


# ============================================================
# MODEL VERSION INFORMATION
# ============================================================

def get_production_model_version():
    """
    Return the MLflow ModelVersion object currently
    assigned to @production.
    """

    return client.get_model_version_by_alias(
        name=MODEL_NAME,
        alias="production"
    )


def get_staging_model_version():
    """
    Return the MLflow ModelVersion object currently
    assigned to @staging.
    """

    return client.get_model_version_by_alias(
        name=MODEL_NAME,
        alias="staging"
    )